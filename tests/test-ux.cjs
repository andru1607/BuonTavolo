const fs=require('fs'),vm=require('vm'),crypto=require('crypto');
const html=fs.readFileSync(__dirname+'/../index.html','utf8');
const js=html.split('<script>')[1].split('</script>')[0];
const handlers={};const storage={};const ui={innerHTML:'',classList:{add(){},remove(){}}};
const context={console,crypto:crypto.webcrypto,localStorage:{getItem:k=>storage[k]??null,setItem:(k,v)=>storage[k]=v},document:{getElementById:k=>ui,addEventListener(type, handler){handlers[type]=handler}},navigator:{},window:{scrollTo(){}},setTimeout,clearTimeout,confirm:()=>true};
vm.createContext(context);vm.runInContext(js,context,{timeout:4000});
const run=code=>vm.runInContext(code,context,{timeout:4000});
const check=(condition,message)=>{if(!condition)throw Error(message)};
check(ui.innerHTML.includes('Ogni ospite'),'welcome editorial UX missing');
check((run('nav()')||[]).length===4,'client menu must have four tabs');
run('switchRole("customer")');check(ui.innerHTML.includes('DINERPASS')||ui.innerHTML.includes('DinerPass'),'passport missing');
check(ui.innerHTML.includes('stamp-rail'),'reward stamps missing');
check((ui.innerHTML.match(/class="stamp stamped"/g)||[]).length===9,'9 stamped reviews expected');
run('switchRole("restaurant")');check(run('nav().length')===4,'restaurant menu must have four tabs');
check(ui.innerHTML.includes('merchant-feature'),'restaurant dashboard missing');
run('changeTab("clients")');
check(!ui.innerHTML.includes('data-action="start-review"'),'directory must not show an unselected guest');
handlers.click({target:{closest(selector){return selector === '[data-action]' ? {dataset:{action:'select-client',id:'CL-10482'}} : null}}});
check(ui.innerHTML.includes('toggle-favorite'),'save client missing');
check(run('db.favorites.length')===0,'favorites must start empty');
run('db.favorites.push("CL-10482");save();render()');check(ui.innerHTML.includes('aria-pressed="true"'),'favorite not marked');
check(run('db.favorites.length')===1,'favorite lost');
run('changeTab("review")');check((ui.innerHTML.match(/data-action="rating"/g)||[]).length===0,'wizard must start with visit verification');
run('state.wizard=2;render()');check((ui.innerHTML.match(/data-action="rating"/g)||[]).length===10,'rating must have 10 choices');
check(ui.innerHTML.includes('8, 9 o 10'),'positive threshold missing');
console.log('PASS: V6 UI, four-tab navigation, passport, nine stamps, favorites and 10-star wizard');
