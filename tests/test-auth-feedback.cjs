'use strict';
const assert = require('node:assert/strict');
const auth = require('../auth-feedback.js');
const msg = (message,code) => auth.explain({message,code});
assert.match(msg('GOODDINER_INVITE_INVALID_OR_USED'), /codice di invito.*scaduto/);
assert.match(msg('GOODDINER_INVITE_EMAIL_REQUIRED'), /codice di invito/);
assert.match(msg('GOODDINER_REGISTRATION_CLOSED'), /temporaneamente sospese/);
assert.match(msg('Email not confirmed'), /confermare/);
assert.match(msg('Invalid login credentials'), /password non corretti/);
assert.match(msg('User already registered'), /potrebbe essere già registrato/);
assert.match(msg('Too many requests'), /troppi tentativi/);
assert.match(msg('bad SQL internals relation auth.users'), /Riprova più tardi/);
assert.doesNotMatch(msg('bad SQL internals relation auth.users'), /SQL|auth\.users|relation/);
assert.equal(auth.emailConfirmed({email:'a@example.test',email_confirmed_at:'2026-11-22T12:00:00Z',is_anonymous:false}),true);
assert.equal(auth.emailConfirmed({email:'a@example.test',email_confirmed_at:null,is_anonymous:false}),false);
assert.equal(auth.emailConfirmed({email:'a@example.test',email_confirmed_at:'2026-11-22T12:00:00Z',is_anonymous:true}),false);
assert.equal(auth.emailConfirmed({email:null,email_confirmed_at:null,is_anonymous:false}),false);
console.log('PASS: Italian safe Supabase Auth errors and verified-email gate');
