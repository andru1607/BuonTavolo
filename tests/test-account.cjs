const fs = require('fs'), vm = require('vm'), assert = require('assert');
const folder = __dirname + '/../';
const js = fs.readFileSync(folder + 'account.js', 'utf8');
const page = fs.readFileSync(folder + 'account.html', 'utf8');
const sql = fs.readFileSync(folder + 'database/schema.sql', 'utf8');
assert(page.includes('id="view"'));
assert(page.includes('id="nav"'));
assert(page.includes('viewport-fit=cover'));
assert(js.includes("r.rating>=8"),'8/10 must be positive');
assert(js.includes('data-rating="${i+1}"'),'1-10 choice');
assert(sql.includes('rating between 1 and 10'));
assert(sql.includes('verified_at is not null'));
assert(sql.includes("claim_visit(p_token uuid, p_restaurant_id uuid)"));
assert(sql.includes('revoke all on table'));
assert(!js.includes('service_role') && !js.includes('secretKey'));
