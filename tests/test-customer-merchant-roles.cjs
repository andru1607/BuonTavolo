'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8');
const app=read('official.js');
const sql=read('database/gooddiner_customer_signup_merchant_invite.sql');
const qa=read('database/gooddiner_customer_signup_merchant_invite_test.sql');
const cfg=read('config.js');
assert.match(cfg,/registrationMode:\s*"invite"/);
assert.match(app,/Nessun codice invito richiesto/);
const customer=app.slice(app.indexOf("if(state.view==='signup-customer')"),app.indexOf("if(state.view==='signup-merchant')"));
const merchant=app.slice(app.indexOf("if(state.view==='signup-merchant')"),app.indexOf("if(state.view==='signin')"));
assert.ok(!customer.includes('inviteField()'),'customer signup must never render invitation input');
assert.ok(merchant.includes('inviteField()'),'merchant signup must still render invitation input');
const signup=app.slice(app.indexOf('async function signupCustomer(form)'),app.indexOf('async function signupMerchant(form)'));
assert.ok(!signup.includes('gd_invite_purpose'),'customer signup must not send merchant metadata');
assert.ok(!signup.includes('signInAnonymously'),'customer registration requires email/password');
assert.match(signup,/data:\{nickname:nick\}/);
assert.match(merchant,/codice invito personale/);
assert.match(sql,/create or replace function gd_private\.enforce_registration_gate\(\)/);
assert.match(sql,/supplied_purpose='merchant' or supplied_code<>''/);
assert.match(sql,/and i\.purpose='merchant'/);
assert.match(sql,/current_user_has_merchant_invite/);
assert.match(sql,/drop policy if exists gd_applications_request/);
assert.match(sql,/current_user_email_confirmed/);
assert.match(qa,/FAIL: customer could apply without merchant invite/);
assert.match(qa,/FAIL: invited merchant not recognized/);
assert.match(qa,/ROLLBACK_GOODDINER_ROLE_QA/);
console.log('PASS: customer free signup form + trusted merchant-only RLS and invitation gate');
